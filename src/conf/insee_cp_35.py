if __name__ == "__main__":
    # Générateur : télécharge le référentiel geo.api.gouv.fr, vérifie sa cohérence
    # avec conf/communes_rm.py, et ré-imprime le module complet sur stdout.
    import datetime
    import os
    import sys
    import unicodedata

    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from connectors.http import session
    from conf.communes_rm import CODES_INSEE_RM, CODES_POSTAUX_RM

    URL = "https://geo.api.gouv.fr/departements/35/communes?fields=nom,code,codesPostaux"

    def _normaliser(texte: str) -> str:
        # Copie locale de filters.geographic.normaliser (l'importer ici créerait
        # un cycle conf -> filters -> conf).
        texte = texte.lower().strip()
        texte = texte.replace("_", " ").replace("-", " ")
        texte = unicodedata.normalize("NFD", texte)
        return "".join(c for c in texte if unicodedata.category(c) != "Mn")

    reponse = session.get(URL, timeout=30)
    reponse.raise_for_status()
    communes = sorted(reponse.json(), key=lambda c: c["code"])

    if len(communes) != 332:
        raise SystemExit(f"Attendu 332 communes dans le 35, reçu {len(communes)} — vérifier l'API")
    codes_insee = {c["code"] for c in communes}
    codes_postaux = {cp for c in communes for cp in c["codesPostaux"]}
    manquants = sorted(CODES_INSEE_RM - codes_insee)
    if manquants:
        raise SystemExit(f"Codes INSEE RM absents du référentiel : {manquants}")
    manquants = sorted(CODES_POSTAUX_RM - codes_postaux)
    if manquants:
        raise SystemExit(f"Codes postaux RM absents du référentiel : {manquants}")
    noms_vers_insee = {}
    for c in communes:
        nom_norm = _normaliser(c["nom"])
        if nom_norm in noms_vers_insee:
            raise SystemExit(f"Nom normalisé en doublon dans le 35 : {nom_norm!r}")
        noms_vers_insee[nom_norm] = c["code"]

    aujourd_hui = datetime.date.today().isoformat()
    lignes = [f"# Données générées le {aujourd_hui} depuis {URL}", ""]
    lignes.append("# code INSEE -> (nom officiel, tuple des codes postaux)")
    lignes.append("COMMUNES_35 = {")
    for c in communes:
        cps = ", ".join(f'"{cp}"' for cp in sorted(c["codesPostaux"]))
        if len(c["codesPostaux"]) == 1:
            cps += ","
        lignes.append(f'    "{c["code"]}": ("{c["nom"]}", ({cps})),')
    lignes.append("}")
    lignes.append("")
    lignes.append("# nom normalisé (minuscules, sans accents, -/_ -> espace) -> code INSEE")
    lignes.append("# (même normalisation que filters.geographic.normaliser)")
    lignes.append("NOMS_35_VERS_INSEE = {")
    for nom_norm, code in sorted(noms_vers_insee.items()):
        lignes.append(f'    "{nom_norm}": "{code}",')
    lignes.append("}")

    # Ré-impression du module : tout ce qui entoure les données est repris tel quel
    # depuis le fichier courant (les marqueurs délimitent le bloc à remplacer).
    marqueur_debut = "# --- DEBUT DONNEES GENEREES (ne pas éditer à la main) ---"
    marqueur_fin = "# --- FIN DONNEES GENEREES ---"
    with open(os.path.abspath(__file__), encoding="utf-8") as f:
        source = f.read()
    avant, _, reste = source.partition(marqueur_debut)
    _, _, apres = reste.partition(marqueur_fin)
    sys.stdout.write(avant + marqueur_debut + "\n\n" + "\n".join(lignes)
                     + "\n\n" + marqueur_fin + apres)
